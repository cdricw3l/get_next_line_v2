#include "../include/libip.h"

uint16_t ft_htons_v1(uint16_t port)
{
    uint16_t p3;

    p3 = 0;
    p3 |= port >> 8;
    p3 |= port << 8;
    return (p3);
}

uint16_t ft_htons_v2(uint16_t port)
{
    return ((port >> 8) | (port << 8));
}