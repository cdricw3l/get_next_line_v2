#include "libft.h"

void	ft_print_bit_32(int n)
{
	int		bit;
	char	c;

	bit = 31;
	while (bit >= 0)
	{
		if((bit + 1) % 8 == 0)
			write(1, " ", 1);
		c = ((n >> bit) & 1) + '0';
		write(1, &c, 1);
		bit--;
	}
	write(1, "\n", 1);
}
